def comment_body(text):
    # Only used for evidence checking, no source text is modified.
    return re.sub(r'【(?:父评论|子评论\d*)｜[^】]*】', '', text)

def facts(source):
    catalog = {e['source_key']:e for e in p.v.supplement.evidence_catalog(source['units'])}
    groups = {}
    for uid, outcome in source['outcomes'].items():
        for vi, view in enumerate(outcome['views']):
            for li, label in enumerate(view['labels']):
                signature = digest([uid,label['tag_id'],label['object'],label['attribute_keys']])
                if signature not in groups:
                    groups[signature] = {'fact_id':'F'+str(len(groups)+1).zfill(3),'unit_id':uid,
                        'tag_id':label['tag_id'],'object':label['object'],
                        'evidence':[{'key':k,'text':catalog[k]['text']} for k in label['attribute_keys']], 'refs':[]}
                groups[signature]['refs'].append({'unit_id':uid,'view_index':vi,'label_index':li,
                    'old_project_id':view['project_id']})
    return list(groups.values())

def own_payload(source):
    # Whitelist, never serialize source/document/old output into Stage A.
    payload={'comment_text':comment_body(source['document']['text']),'known_projects':known_projects(),
        'facts':[fact_payload(f) for f in facts(source)]}
    for fact in payload['facts']:
        for evidence in fact['evidence']:
            evidence['text']=comment_body(evidence['text'])
    return payload

def fact_payload(f):
    t=TM[f['tag_id']]
    return {k:copy.deepcopy(f[k]) for k in ('fact_id','tag_id','evidence')} | {
        'tag_name':t['emphasis'],'tag_definition':t['instruction']}

def brand_guard(bindings, text):
    """Never turn a developer-only mention into a specific project in Stage A.

    This is not a final alias mapping: absence of a known name-family clue
    sends a claimed explicit identity to parent disambiguation rather than
    rejecting the source. Unknown explicitly named OTHER projects stay allowed.
    """
    families={'P01':('华润',('臻','澐','云雅苑')),'C01':('建发',('海晏','海宴')),
        'C02':('中海',('安澜','安和','圆明')),'C05':('保利',('熙瑞','西瑞','瑞璟','半壁店'))}
    changes=[];body=comment_body(text)
    for b in bindings:
        for project in b['projects']:
            if project['id'] not in families:continue
            brand,names=families[project['id']]
            if not any(x in body for x in names):
                changes.append({'fact_id':b['fact_id'],'model_decision_preserved':copy.deepcopy(b),
                    'reason':'评论发言无该具体楼盘的名称线索；品牌、物业形态或配置不能单独锁定楼盘，改入父文消歧。'})
                b.update(decision='unresolved',projects=[],method='unresolved',reason=changes[-1]['reason']);break
    return changes

def parent_fields(source):
    row=source['document']['parent']; out={}
    for field in ('文章标题','文章内容','文章视频内容','文章图片信息','文章标签'):
        value=str(row.get(field) or '').strip()
        if value and value.lower() not in ('nan','none','null') and value not in out.values():out[field]=value
    return out

def project_schema(context=False):
    fields={'id':enum([*PM,'OTHER']),'name':TEXT,'quote':TEXT}
    if context:fields['evidence_field']=TEXT
    return obj(fields)

def binding_schema(ids, context=False):
    return obj({'bindings':arr(obj({'fact_id':enum(ids),
        'decision':enum(['context_resolved','ambiguous'] if context else ['explicit','unresolved']),
        'projects':arr(project_schema(context)), 'reason':TEXT}))})

def validate_projects(projects, fields):
    errors=[]
    for project in projects:
        pid=project['id']; name=project['name'];quote=project['quote']
        if pid in PM and name!=PM[pid]['name']:errors.append('noncanonical_project_name')
        if not name.strip() or not quote.strip():errors.append('empty_project_identity')
        if pid=='OTHER' and name.strip() in ('未知楼盘','某楼盘','未命名项目','未知项目','不详','未知'):
            errors.append('generic_unknown_is_not_explicit_named_project')
        field=project.get('evidence_field','comment_text')
        if field not in fields or quote not in fields[field]:errors.append('nonliteral_project_quote')
    if len({(x['id'],x['name']) for x in projects})!=len(projects):errors.append('duplicate_projects')
    return errors

def validate_bindings(raw, ids, fields, context=False):
    values=raw['bindings']; errors=[]
    if sorted(x['fact_id'] for x in values)!=sorted(ids):errors.append('missing_or_duplicate_fact')
    for x in values:
        resolved=x['decision'] in ('explicit','context_resolved')
        if bool(x['projects'])!=resolved:errors.append('decision_project_inconsistent')
        if not x['reason'].strip():errors.append('empty_reason')
        errors+=validate_projects(x['projects'],fields)
    return errors

def request(runner, system, payload, schema, doc, phase, validate):
    key=digest([VERSION,system,payload,schema]);file=OUT/'stages'/(key+'.json')
    if file.exists():
        saved=p.read(file)
        assert saved['input_sha256']==digest(payload)
        assert not validate(saved['response'])
        for proof in saved['formal_calls']:assert sha(proof['file'])==proof['sha256']
        return saved['response'], reference(file)
    current=copy.deepcopy(payload); history=[]
    for attempt in range(3):
        raw,metric=runner.call(system,dict(current,output_contract=schema),doc,'紧凑评论项目复核-'+phase,response_schema=schema)
        cf=runner.output/'calls'/(metric['request_key']+'.json')
        history.append(reference(cf))
        if raw is None:raise RuntimeError('API stage failed: '+str(metric.get('http_status'))+' '+metric.get('error',''))
        original=copy.deepcopy(raw);normalizations=[]
        if phase=='P-父文具体对象' and isinstance(raw,dict) and isinstance(raw.get('projects'),list):
            groups={}
            for x in raw['projects']:groups.setdefault((x.get('id'),x.get('name')),[]).append(x)
            if any(len(xs)>1 for xs in groups.values()):
                raw=copy.deepcopy(raw)
                raw['projects']=[max(xs,key=lambda x:len(x.get('quote',''))) for xs in groups.values()]
                normalizations=[{'operation':'merge_identical_project_ids_preserve_all_quotes_in_original_response',
                    'projects':xs} for xs in groups.values() if len(xs)>1]
        errors=issues(raw,schema)
        if not errors:errors=validate(raw)
        if not errors:
            saved={'version':VERSION,'phase':phase,'input_sha256':digest(payload),'payload':payload,
                'system':system,'schema':schema,'response':raw,'formal_calls':history,'created_at':time.time()}
            if normalizations:saved.update(original_response=original,normalizations=normalizations)
            save(file,saved);return raw,reference(file)
        current=dict(payload,previous_response=raw,protocol_errors=errors,
            field_repair_attempt=attempt+2,
            repair_instruction='只修复所列结构/逐字引文问题；不为通过校验强行改变语义决定。quote只摘发言正文，不带结构标记/昵称。明确案名缺失则unresolved，不能用风格配置或未知楼盘强判。')
    raise RuntimeError('Protocol stage not completed: '+str(errors))

def resolve(source, runner):
    f=facts(source);ids=[x['fact_id'] for x in f];payload=own_payload(source)
    own,proof=request(runner,A_SYSTEM,payload,binding_schema(ids),source['document'],'A-隔离评论',
        lambda raw:validate_bindings(raw,ids,{'comment_text':comment_body(source['document']['text'])}))
    bindings={x['fact_id']:dict(copy.deepcopy(x),method='comment_explicit' if x['decision']=='explicit' else 'unresolved') for x in own['bindings']}
    guard_events=brand_guard(list(bindings.values()),source['document']['text'])
    proofs=[proof]; unresolved=[x for x in f if bindings[x['fact_id']]['decision']=='unresolved']
    for x in bindings.values():
        for project in x['projects']:project['evidence_field']='comment_text'
    parent=None
    if unresolved:
        fields=parent_fields(source)
        ps=obj({'projects':arr(project_schema(True)),'reason':TEXT})
        parent,pp=request(runner,P_SYSTEM,{'parent_fields':fields,'known_projects':known_projects()},ps,
            source['document'],'P-父文具体对象',lambda raw:validate_projects(raw['projects'],fields))
        proofs.append(pp)
        if len(parent['projects'])==1:
            for x in unresolved:
                bindings[x['fact_id']]={'fact_id':x['fact_id'],'decision':'context_resolved',
                    'projects':copy.deepcopy(parent['projects']),'method':'unique_parent_inherited',
                    'reason':'评论自身无明确具体楼盘，按用户规则继承父文章唯一主讲项目；父文仅用于身份归属。'}
        else:
            bp={'comment_text':source['document']['text'],'parent_fields':fields,'parent_projects':parent['projects'],
                'known_projects':known_projects(),'requested_facts':[fact_payload(x) for x in unresolved]}
            bids=[x['fact_id'] for x in unresolved]
            ctx,cp=request(runner,B_SYSTEM,bp,binding_schema(bids,True),source['document'],'B-多项目消歧',
        lambda raw:validate_bindings(raw,bids,dict(fields,comment_text=comment_body(source['document']['text'])),True))
            proofs.append(cp)
            for x in ctx['bindings']:bindings[x['fact_id']]=dict(x,method='parent_context_resolved' if x['projects'] else 'ambiguous')
    return {'version':VERSION,'record_id':source['record_id'],'source_digest':digest(source),
        'comment_text_sha256':hashlib.sha256(source['document']['text'].encode()).hexdigest(),
        'facts':f,'bindings':list(bindings.values()),'formal_stage_proofs':proofs,'parent':parent,
        'identity_guard_events':guard_events,'labels_regenerated':False,'slice_regenerated':False,'created_at':time.time()}

def label_fingerprint(source):
    return sorted(digest([uid,l]) for uid,o in source['outcomes'].items() for v in o['views'] for l in v['labels'])

def apply_overlay(source, overlay):
    assert overlay['source_digest']==digest(source)
    updated=copy.deepcopy(source); routes={x['fact_id']:x for x in overlay['bindings']}; parked=[]
    for uid,outcome in updated['outcomes'].items():
        grouped={}
        for f in overlay['facts']:
            if f['unit_id']!=uid:continue
            r=routes[f['fact_id']]
            targets=r['projects']
            for ref in f['refs']:
                old=source['outcomes'][uid]['views'][ref['view_index']]
                label=old['labels'][ref['label_index']]
                for target in targets or [None]:
                    if target is None or target['id']=='OTHER':
                        parked.append({'unit_id':uid,'fact_id':f['fact_id'],'original_project_id':old['project_id'],
                            'label':copy.deepcopy(label),'resolution':copy.deepcopy(r),'reason':'ambiguous' if target is None else 'outside_four_projects'})
                        continue
                    pid=target['id'];item=grouped.setdefault(pid,{'project_id':pid,'labels':[],
                        'original_view_candidates':[],'summary':'','expressions':[],'emotions':[]})
                    # Existing tag semantics retained. Old identity retained separately, never mislabelled as new proof.
                    revised=copy.deepcopy(label)
                    revised['project_identity_previous']=revised['project_identity']
                    revised['project_identity']={'context_source':'source' if target['evidence_field']=='comment_text' else 'parent_title' if target['evidence_field']=='文章标题' else 'parent',
                        'quote':target['quote'],'reason':r['reason']}
                    revised['project_attribution_proof']={'version':overlay['version'],'fact_id':f['fact_id'],'method':r['method'],
                        'evidence_field':target['evidence_field'],'project_id':pid,'project_name':PM[pid]['name'],
                        'project_role':PM[pid]['role'],'formal_stage_proofs':overlay['formal_stage_proofs']}
                    identity=digest([revised['tag_id'],revised['object'],revised['attribute_keys'],revised['context_keys']])
                    if identity not in {x[0] for x in item.get('_seen',[])}:
                        item.setdefault('_seen',[]).append((identity,True));item['labels'].append(revised)
                    if old not in item['original_view_candidates']:item['original_view_candidates'].append(old)
        outcome['views']=list(grouped.values())
        for view in outcome['views']:
            view.pop('_seen',None)
            # Only retain an unchanged view summary if no source objects crossed.
            candidates=view.pop('original_view_candidates')
            original=next((x for x in candidates if x['project_id']==view['project_id']),None)
            before=source['outcomes'][uid]['views']
            unchanged=original is not None and len(candidates)==1 and len(view['labels'])==len(original['labels']) and all(
                any(l['tag_id']==o['tag_id'] and l['object']==o['object'] and l['attribute_keys']==o['attribute_keys'] for o in original['labels']) for l in view['labels'])
            if unchanged:
                for key in ('summary','expressions','emotions'):view[key]=copy.deepcopy(original[key])
            else:view['summary_project_repair_required']=True
        # Facts refer to preserved dictionary labels, including parked entries, not fictional new labels.
    updated['project_attribution_parked_labels']=parked
    updated['project_attribution_revision']={'version':VERSION,'record_id':source['record_id'],'base_source_digest':digest(source),
        'overlay_file':overlay.get('overlay_file',''),'partial_cohort_review':True,
        'not_legacy_contract_claim':True}
    updated['state']='accepted' if any(o['views'] for o in updated['outcomes'].values()) else 'excluded_after_project_review'
    return updated

def repair_summaries(source, revised, runner):
    for uid,outcome in revised['outcomes'].items():
        pending=[v for v in outcome['views'] if v.get('summary_project_repair_required')]
        if not pending:continue
        from voc_metadata_completion_v99 import ALLOWED
        sc=obj({'views':arr(obj({'project_id':enum([x['project_id'] for x in pending]),'summary':TEXT,
            'expressions':arr(enum(sorted(ALLOWED['表达类型']))),'emotions':arr(enum(sorted(ALLOWED['情绪态度'])))}))})
        payload={'comment_text':source['document']['text'], 'project_bindings':[{'project_id':v['project_id'],
            'project_name':PM[v['project_id']]['name'],'label_facts':[{'tag_id':l['tag_id'],'object':l['object'],
                'evidence_keys':l['attribute_keys'],'assignment':l['project_attribution_proof']} for l in v['labels']]} for v in pending],
            'source_evidence':p.v.supplement.evidence_catalog(source['units'])}
        def validate(raw):
            es=[]
            if sorted(x['project_id'] for x in raw['views'])!=sorted(x['project_id'] for x in pending):es.append('missing_or_duplicate_view')
            if any(not x['summary'].strip() or not x['expressions'] or not x['emotions'] for x in raw['views']):es.append('missing_view_fields')
            return es
        raw,proof=request(runner,'项目映射已单独裁决，本次仅按给定评论及项目分配生成每项目简短摘要、表达类型及情绪态度。只概括该项目真实对应的标签事实，不把其他楼盘事实搬来。不重新选择标签，不引入父文事实，保留疑问/比较/预测/否定。只输出最终JSON。',payload,sc,source['document'],'S-归属变化摘要修复',validate)
        for x in raw['views']:
            view=next(v for v in pending if v['project_id']==x['project_id']);view.update(x)
            view.pop('summary_project_repair_required');view['summary_project_repair_proof']=proof
    return revised
