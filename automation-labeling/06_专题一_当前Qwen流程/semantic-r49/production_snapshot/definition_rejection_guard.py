import re


def added_requirement_reason(reason,definition=None):
    # Re-review only: never auto-accept a disputed label. The real dictionary
    # says height, not necessarily clear/net height or one numbered dwelling.
    if isinstance(definition,dict):
        direction=' '.join(str(definition.get(k) or '') for k in ('emphasis','l3','l4','l5','instruction'))
        if ('层高' in direction and '净高' not in direction and
                re.search(r'非套内净高|非.{0,10}净高|非特定户型|(?:不是|不属于).{0,12}净高',str(reason or ''))):
            return True
    if re.search(r'特定.{0,12}(?:房源|待售|楼盘|房地产单元)|板块.{0,15}不等于.{0,8}(?:项目|楼盘)|宏观区域.{0,25}无法',str(reason or '')):
        return True
    if re.search(r'仅为主观体验|仅为主观感受|不符合.{0,12}明确口径',str(reason or '')):
        return True
    if re.search(r'未.{0,24}(?:选择过程|购买意向|购房意向)|未表达.{0,20}关注.*决策因素',str(reason or '')):
        return True
    return bool(re.search(r'(?:已|应由).{0,30}覆盖|非典型.{0,12}交通噪音|无明确道路|(?:未提供|无明确).{0,30}监测数据|仅为定性描述|(?:仅|只|只是).{0,16}(?:询问|提问|疑问)|(?:未|没有|缺乏).{0,20}(?:明确关注|关注点|肯定性表述)|不是.{0,15}(?:客观事实|确定的规划)|未.{0,12}(?:最终决定|具体购买行动)', str(reason or '')))


