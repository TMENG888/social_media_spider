import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import mysql from 'mysql2/promise';
import { dedupePostsGlobal } from './wechat-dedupe.mjs';

const args = {};
for (let index = 2; index < process.argv.length; index += 1) {
  if (!process.argv[index].startsWith('--')) continue;
  const key = process.argv[index].slice(2);
  const next = process.argv[index + 1];
  args[key] = !next || next.startsWith('--') ? true : process.argv[++index];
}

const output = path.resolve(String(args.output || path.join(process.cwd(), 'wechat_post_dedupe_map_values.sql')));
const inputJsonl = args['input-jsonl'] ? path.resolve(String(args['input-jsonl'])) : null;
const inputCsv = args['input-csv'] ? path.resolve(String(args['input-csv'])) : null;
const sqlText = (value) => value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "''")}'`;
let rows;

const readCsv = (file) => {
  const source = fs.readFileSync(file, 'utf8').replace(/^\uFEFF/u, '');
  const table = [];
  let row = [], field = '', quoted = false;
  for (let index = 0; index < source.length; index += 1) {
    const character = source[index];
    if (quoted) {
      if (character === '"' && source[index + 1] === '"') { field += '"'; index += 1; }
      else if (character === '"') quoted = false;
      else field += character;
    } else if (character === '"') quoted = true;
    else if (character === ',') { row.push(field); field = ''; }
    else if (character === '\n') { row.push(field.replace(/\r$/u, '')); table.push(row); row = []; field = ''; }
    else field += character;
  }
  if (field || row.length) { row.push(field.replace(/\r$/u, '')); table.push(row); }
  const [headers, ...data] = table;
  return data.filter((values) => values.some((value) => value !== '')).map((values) => Object.fromEntries(headers.map((header, index) => [header, values[index] ?? ''])));
};

if (inputJsonl) {
  rows = fs.readFileSync(inputJsonl, 'utf8').split(/\r?\n/u).filter(Boolean).map(JSON.parse);
} else if (inputCsv) {
  rows = readCsv(inputCsv);
} else {
  const host = process.env.MYSQL_HOST || 'mysql.example.com';
  const port = Number(process.env.MYSQL_PORT || 3306);
  const database = process.env.MYSQL_DATABASE || 'social';
  const user = process.env.MYSQL_USER;
  const password = process.env.MYSQL_PASSWORD;
  if (!user || !password) throw new Error('MYSQL_USER 和 MYSQL_PASSWORD 未设置；脚本只读取数据库并生成 SQL，不会删除或更新数据');
  const connection = await mysql.createConnection({host, port, user, password, database, charset:'utf8mb4', dateStrings:true, supportBigNumbers:true, bigNumberStrings:true, connectTimeout:15000});
  try {
    const [result] = await connection.query("SELECT `id`,`文章id`,`文章链接`,`文章内容`,`文章时间地点`,`文章获取时间`,`关键词`,`项目`,`作者名字`,`平台` FROM `ods_social_media_post` WHERE `平台`='微信公众号'");
    rows = result.map((row) => ({...row, id:String(row.id)}));
  } finally {
    await connection.end();
  }
}

const result = dedupePostsGlobal(rows);
const mappings = result.audit.filter((item) => item.duplicateId != null && item.survivorId != null && String(item.duplicateId) !== String(item.survivorId));
const rowsById = new Map(rows.filter((row) => row.id != null).map((row) => [String(row.id), row]));
// These raw hashes are deletion guards. A row changed after map generation
// fails closed and must be analysed again before it can be deleted.
const bodyHash = (row) => crypto.createHash('sha256').update(String(row?.['文章内容'] ?? ''), 'utf8').digest('hex');
const header = [
  `-- Generated by build-wechat-dedupe-map.mjs at ${new Date().toISOString()}`,
  `-- Read-only analysis source rows: ${rows.length}; mappings: ${mappings.length}`,
  'SET NAMES utf8mb4;',
  'CREATE TABLE IF NOT EXISTS `wechat_post_dedupe_map` (',
  '  `duplicate_id` BIGINT NOT NULL,',
  '  `survivor_id` BIGINT NOT NULL,',
  '  `reason` VARCHAR(32) NOT NULL,',
  '  `similarity` DECIMAL(9,6) NOT NULL,',
  '  `duplicate_url` LONGTEXT NULL,',
  '  `survivor_url` LONGTEXT NULL,',
  '  `duplicate_body_sha256` CHAR(64) NULL,',
  '  `survivor_body_sha256` CHAR(64) NULL,',
  '  `duplicate_keyword` VARCHAR(100) NULL,',
  '  `duplicate_project` LONGTEXT NULL,',
  '  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,',
  "  `status` VARCHAR(20) NOT NULL DEFAULT 'pending',",
  '  `applied_at` DATETIME NULL,',
  '  PRIMARY KEY (`duplicate_id`),',
  '  KEY `idx_wechat_dedupe_survivor` (`survivor_id`)',
  ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
  "SET @has_duplicate_body_hash := (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='wechat_post_dedupe_map' AND COLUMN_NAME='duplicate_body_sha256');",
  "SET @dedupe_ddl := IF(@has_duplicate_body_hash=0,'ALTER TABLE wechat_post_dedupe_map ADD COLUMN duplicate_body_sha256 CHAR(64) NULL AFTER survivor_url','SELECT 1');",
  'PREPARE dedupe_stmt FROM @dedupe_ddl; EXECUTE dedupe_stmt; DEALLOCATE PREPARE dedupe_stmt;',
  "SET @has_survivor_body_hash := (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='wechat_post_dedupe_map' AND COLUMN_NAME='survivor_body_sha256');",
  "SET @dedupe_ddl := IF(@has_survivor_body_hash=0,'ALTER TABLE wechat_post_dedupe_map ADD COLUMN survivor_body_sha256 CHAR(64) NULL AFTER duplicate_body_sha256','SELECT 1');",
  'PREPARE dedupe_stmt FROM @dedupe_ddl; EXECUTE dedupe_stmt; DEALLOCATE PREPARE dedupe_stmt;',
].join('\n');

const statements = [];
for (let index = 0; index < mappings.length; index += 250) {
  const chunk = mappings.slice(index, index + 250);
  statements.push(`INSERT INTO \`wechat_post_dedupe_map\` (\`duplicate_id\`,\`survivor_id\`,\`reason\`,\`similarity\`,\`duplicate_url\`,\`survivor_url\`,\`duplicate_body_sha256\`,\`survivor_body_sha256\`,\`duplicate_keyword\`,\`duplicate_project\`) VALUES\n${chunk.map((item) => `(${sqlText(item.duplicateId)},${sqlText(item.survivorId)},${sqlText(item.reason)},${Number(item.similarity || 0).toFixed(6)},${sqlText(item.duplicateUrl)},${sqlText(item.survivorUrl)},${sqlText(bodyHash(rowsById.get(String(item.duplicateId))))},${sqlText(bodyHash(rowsById.get(String(item.survivorId))))},${sqlText(item.duplicateKeyword)},${sqlText(item.duplicateProject)})`).join(',\n')}\nON DUPLICATE KEY UPDATE \`survivor_id\`=VALUES(\`survivor_id\`),\`reason\`=VALUES(\`reason\`),\`similarity\`=VALUES(\`similarity\`),\`duplicate_url\`=VALUES(\`duplicate_url\`),\`survivor_url\`=VALUES(\`survivor_url\`),\`duplicate_body_sha256\`=VALUES(\`duplicate_body_sha256\`),\`survivor_body_sha256\`=VALUES(\`survivor_body_sha256\`),\`duplicate_keyword\`=VALUES(\`duplicate_keyword\`),\`duplicate_project\`=VALUES(\`duplicate_project\`),\`status\`='pending',\`applied_at\`=NULL;`);
}
fs.writeFileSync(output, `${header}\n\n${statements.join('\n\n')}\n`, 'utf8');
console.log(JSON.stringify({sourceRows:rows.length, survivorRows:result.records.length, duplicateMappings:mappings.length, output}, null, 2));

