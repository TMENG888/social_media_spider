import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {ProductionOutputRecorder,changedFields,meaningfulHint,finishOutput,recoverCommittedOutputs} from '../src/production-output.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'wechat-output-test-'));
const identity={computer:'test-host',worker:'worker-test',consumer:'test-consumer',runId:'observability-unit-test',generation:'test-generation',keyword:'test-keyword'};
const row={id:'123','文章id':'article-a','文章链接':'https://weixin.qq.com/sph/TestOnly','平台':'微信视频号','项目':'test','文章标题':'Title','文章视频内容':null,'文章点赞数':3,'文章获取时间':new Date('2026-10-01T00:00:00Z')};
function recorder(name){return new ProductionOutputRecorder({root:path.join(root,name),identity});}
const unchanged=recorder('unchanged');
const repeated={...row,'文章获取时间':new Date(),'关键词':'other'};
assert.equal(meaningfulHint(row,{'文章点赞数':'3','文章获取时间':new Date()}),false);
assert.deepEqual(changedFields(row,repeated),[]);
unchanged.track('ods_social_media_post',row,repeated);assert.equal(unchanged.prepare(),null);
const added=recorder('insert');added.track('ods_social_media_post',null,row);
const event=added.prepare();assert.equal(event.items[0].operation,'insert');assert.deepEqual(event.items[0].types,['metadata']);
assert.equal(fs.existsSync(path.join(added.root,'pending',event.eventId+'.json')),false);
assert.throws(()=>added.confirmRows({'ods_social_media_post:123':row}),/Commit receipt/);
added.markCommitted();
assert.throws(()=>added.confirmRows({'ods_social_media_post:123':{...row,'文章标题':'Wrong'}}),/mismatch/);
assert.equal(fs.existsSync(path.join(added.root,'pending',event.eventId+'.json')),false);
added.confirmRows({'ods_social_media_post:123':row});
assert.equal(fs.existsSync(path.join(added.root,'pending',event.eventId+'.json')),true);
assert.equal(event.readbackVerified,true);
const subtitle=recorder('subtitle');
const withSubtitle={...row,'文章视频内容':'这是用于测试的字幕'};
subtitle.track('ods_social_media_post',row,withSubtitle,{approved:true});
const subevent=subtitle.prepare();assert.deepEqual(subevent.items[0].types,['subtitle']);assert.equal(subevent.items[0].subtitleApproval,'manual_approval');
assert.equal(JSON.stringify(subevent).includes('这是用于测试的字幕'),false);
const comment=recorder('comment');
comment.track('ods_social_media_comment',null,{id:'456','文章id':'article-a','评论id':'c1','评论内容':'测试评论','平台':'微信视频号'});
assert.deepEqual(comment.prepare().items[0].types,['comment']);
const coalesced=recorder('coalesced');
coalesced.track('ods_social_media_post',row,{...row,'文章标题':'Interim'});
coalesced.track('ods_social_media_post',{...row,'文章标题':'Interim'},row);
assert.equal(coalesced.prepare(),null);
const failed=recorder('failed');failed.track('ods_social_media_post',null,row);failed.prepare();failed.abort();
assert.equal(failed.prepared.event.outcome,'rolled_back');
const ambiguous=recorder('ambiguous');ambiguous.track('ods_social_media_post',null,row);ambiguous.prepare();ambiguous.commitAttempted=true;ambiguous.abort();
assert.equal(ambiguous.prepared.event.outcome,'commit_outcome_unknown_do_not_publish');
const bad=recorder('badreadback');bad.track('ods_social_media_post',row,withSubtitle);bad.prepare();bad.flush=()=>assert.fail('Must not upload failed readback');
const result=await finishOutput(bad,{execute:async()=>[[{...row,'文章视频内容':'other'}]]});
assert.equal(result.state,'verification_pending');
const recovered=await recoverCommittedOutputs({execute:async()=>[[withSubtitle]]},bad.root);
assert.equal(recovered,1);
console.log(JSON.stringify({tests:'passed',checks:16,fixtureDirectory:root,productionDatabaseChanged:false,productionRedisChanged:false}));
